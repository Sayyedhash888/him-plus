const manifest = [];
for (const theme of THEMES) {
  const fileName = `him-${theme.id}-color-theme.json`;
  fs.writeFileSync(
    path.join(outDir, fileName),
    `${JSON.stringify(buildTheme(theme), null, 2)}\n`,
  );
  manifest.push({
    label: `HIM+ ${theme.name}`,
    uiTheme: theme.mode === 'light' ? 'vs' : 'vs-dark',
    path: `./themes/${fileName}`,
  });
}
fs.writeFileSync(
  path.join(outDir, 'manifest.json'),
  `${JSON.stringify(manifest, null, 2)}\n`,
);
console.log(`generated ${manifest.length} HIM+ themes`);